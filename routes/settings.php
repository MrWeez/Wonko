<?php

use App\Http\Middleware\EnsurePasswordChange;
use Illuminate\Support\Facades\Route;

Route::middleware(['auth', EnsurePasswordChange::class])->group(function () {
    Route::redirect('settings', 'settings/profile');

    Route::livewire('settings/profile', 'pages::settings.profile')->name('profile.edit');
});

Route::middleware(array_filter(['auth', config('auth.email_verification_required') ? 'verified' : null, EnsurePasswordChange::class]))->group(function () {
    Route::livewire('settings/appearance', 'pages::settings.appearance')->name('appearance.edit');

    Route::livewire('settings/security', 'pages::settings.security')
        ->middleware([
            'password.confirm',
        ])
        ->name('security.edit');
});

Route::get('.well-known/passkey-endpoints', function () {
    return response()->json([
        'enroll' => route('security.edit'),
        'manage' => route('security.edit'),
    ]);
})->name('well-known.passkeys');
